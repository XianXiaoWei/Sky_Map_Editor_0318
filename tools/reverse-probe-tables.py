#!/usr/bin/env python3
"""Capture the original deterministic 32-pixel cube seam table, SHA gated.
The table is stored losslessly as uint16; execution still uses original uint32.
"""
import base64
import hashlib
import pathlib
import struct
import subprocess
import sys
import tempfile
from native import Native

n = Native(sys.argv[1])
with tempfile.TemporaryDirectory(prefix='sky-probe-table-') as temporary:
    runner = str(pathlib.Path(temporary) / 'oracle')
    subprocess.run(['x86_64-linux-gnu-gcc', '-O2', '-static', 'tools/native-probe-oracle.c', '-o', runner], check=True)
    result = subprocess.run(['qemu-x86_64', '-cpu', 'max', runner, sys.argv[1], '--table'], check=True, capture_output=True).stdout
if len(result) != 132480:
    raise ValueError('Unexpected original table output size')
table = struct.unpack('<32736I', result[:130944])
cursor = 0
for size in [16, 8, 4, 2, 1]:
    count = size * size * 6 * 16
    source_start = 8192 - 8 * (size * 2) ** 2
    source_end = 8192 - 8 * size ** 2
    if not all(source_start <= i < source_end for i in table[cursor:cursor+count]):
        raise ValueError('Original table does not refer exclusively to the preceding mip')
    cursor += count
digest = hashlib.sha256(result[:130944]).hexdigest()
if digest != '1d2a90820caca3d3b25eae8a12e557b75cf56379c851edb9d1053e812aa9ea2e':
    raise ValueError('Original probe constructor output changed')
def literal(data):
    text = base64.b64encode(data).decode()
    return '\n  + '.join(repr(text[i:i+120]) for i in range(0, len(text), 120))
packed = struct.pack('<32736H', *table)
source = f'''// Generated by tools/reverse-probe-tables.py from the original constructor.
// Fixed 32x32 cube: five 16-tap cross-face mip tables, NOT scene probe colors.
export const PROBE_EXECUTABLE_SHA256 = '{n.digest}';
export const PROBE_TABLE_SHA256 = '{digest}'; // Original uint32 little-endian
export const PROBE_HALF_TABLE_SHA256 = '{hashlib.sha256(result[130944:]).hexdigest()}';
function decode(value: string) {{ return Uint8Array.from(atob(value), c => c.charCodeAt(0)); }}
const indices = decode({literal(packed)});
const view = new DataView(indices.buffer);
export const probeMipIndices = Uint16Array.from({{length: 32736}}, (_, i) => view.getUint16(i * 2, true));
const half = decode({literal(result[130944:])});
const halfView = new DataView(half.buffer);
export const probeHalfBase = Uint16Array.from({{length: 512}}, (_, i) => halfView.getUint16(i * 2, true));
export const probeHalfShift = half.subarray(1024);
'''
pathlib.Path('src/core/probe-tables.ts').write_text(source)
print({'indices': len(table), 'tableSha256': digest, 'sourceBytes': len(source)})
