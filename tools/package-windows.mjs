import asar from '@electron/asar';
import fs from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
const pkg = JSON.parse(await fs.readFile('package.json', 'utf8'));
execFileSync('python3', ['tools/build-vulkan.py', '--windows'], { stdio: 'inherit' });
const version = pkg.devDependencies.electron.replace(/^[~^]/, ''), release = path.resolve('release'), target = path.join(release, 'SkyMapEditor-win32-x64'), staging = path.join(release, 'app');
await fs.mkdir(release, { recursive: true }); await fs.mkdir(staging, { recursive: true });
await fs.cp('dist', path.join(staging, 'dist'), { recursive: true });
await fs.writeFile(path.join(staging, 'package.json'), JSON.stringify({ name: 'sky-map-editor', productName: 'Sky 地图编辑器', version: pkg.version, main: 'dist/main.cjs' }));
const artifact = `electron-v${version}-win32-x64.zip`, archive = path.join(release, artifact);
const checksums = JSON.parse(await fs.readFile('node_modules/electron/checksums.json', 'utf8'));
const expected = checksums[artifact]; if (!expected) throw new Error('Electron package does not include the expected artifact checksum');
async function validArchive() { try { return crypto.createHash('sha256').update(await fs.readFile(archive)).digest('hex') === expected; } catch { return false; } }
if (!await validArchive()) execFileSync('curl', ['--fail', '--location', '--retry', '3', '--connect-timeout', '20', '--max-time', '240', '--silent', '--show-error', `https://github.com/electron/electron/releases/download/v${version}/${artifact}`, '--output', archive], { stdio: 'inherit' });
if (!await validArchive()) throw new Error('Electron Windows artifact SHA-256 mismatch');
await fs.mkdir(target, { recursive: true });
execFileSync('python3', ['-c', 'import zipfile,sys; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])', archive, target]);
await asar.createPackage(staging, path.join(target, 'resources', 'app.asar'));
await fs.mkdir(path.join(target, 'resources', 'native'), { recursive: true });
await fs.copyFile('dist/native/sky-vulkan.exe', path.join(target, 'resources', 'native', 'sky-vulkan.exe'));
await fs.rename(path.join(target, 'electron.exe'), path.join(target, 'SkyMapEditor.exe'));
await fs.copyFile('README.md', path.join(target, '使用说明.md'));
await fs.mkdir(path.join(target, 'docs'), { recursive: true });
for (const name of ['实现清单.md', '思维导图.html', '思维导图.md', '材质逆向进展.md', 'shader-audit.json', 'material-evidence.json', '交付状态.json']) await fs.copyFile(path.join('docs', name), path.join(target, 'docs', name));
const out = path.join(release, 'SkyMapEditor-Windows-x64.zip');
execFileSync('python3', ['-c', 'import pathlib,zipfile,sys; p=pathlib.Path(sys.argv[1]); z=zipfile.ZipFile(sys.argv[2],"w",zipfile.ZIP_DEFLATED); [z.write(f,f.relative_to(p.parent)) for f in p.rglob("*") if f.is_file()]; z.close()', target, out], { stdio: 'inherit' });
console.log(out);
